// Vendor-neutral camera contract. Nothing in here may name a camera vendor, SDK, transport or protocol — those
// belong inside a concrete provider (e.g. a future SonyCameraProvider).

export const CAMERA_STATES = ['DISCONNECTED', 'CONNECTING', 'CONNECTED', 'CAPTURING', 'ERROR'] as const;
export type CameraState = (typeof CAMERA_STATES)[number];

export type CameraErrorCode = 'NOT_CONNECTED' | 'BUSY' | 'CAPTURE_FAILED' | 'CAPTURE_TIMEOUT' | 'CONNECT_FAILED' | 'INVALID_REQUEST'
  /** The machine lacks the camera driver/runtime this provider needs (an installation fact, not a camera fault). */
  | 'DRIVER_UNAVAILABLE'
  /** The provider's own settings cannot select a camera unambiguously (an operator fault). */
  | 'CONFIG_ERROR';

export interface CameraStatus {
  state: CameraState;
  /** Short, vendor-neutral, safe-to-display reason when state is ERROR (never a path, stack or secret). */
  errorCode?: CameraErrorCode;
  errorMessage?: string;
}

export interface CaptureRequest {
  /** Opaque id supplied by the caller for tracing; the bridge never interprets it. */
  correlationId: string;
  /** Informational only — the bridge holds no tag/ERP business rules. */
  tagNumber?: string;
  imageType?: string;
  /** Budget for the whole shutter-to-bytes operation. A provider should abandon its SDK call and throw
   *  CameraError('CAPTURE_TIMEOUT') when it elapses; the bridge enforces the same bound independently. */
  timeoutMs?: number;
}

export interface CapturedImage {
  data: Buffer;
  mimeType: string;
  /** Generated by the provider; never derived from caller input. */
  filename: string;
  width: number;
  height: number;
  capturedAt: Date;
}

/**
 * What a real camera implementation must provide — and ALL it is given. A provider never sees an ERP user, company, branch,
 * tag record, station credential, storage location or command queue; it turns "take a picture" into bytes or a CameraError.
 *   connect()/disconnect()  idempotent; connect() throws CONNECT_FAILED (camera missing / refused)
 *   getStatus()             cheap, never throws, safe to poll every heartbeat
 *   capture()               one at a time (BUSY if a capture is running), NOT_CONNECTED when unplugged,
 *                           CAPTURE_TIMEOUT / CAPTURE_FAILED otherwise; honours request.timeoutMs
 */
export interface CameraProvider {
  getStatus(): Promise<CameraStatus>;
  connect(): Promise<void>;
  disconnect(): Promise<void>;
  capture(request: CaptureRequest): Promise<CapturedImage>;
}

export class CameraError extends Error {
  constructor(public readonly code: CameraErrorCode, message: string) {
    super(message);
    this.name = 'CameraError';
  }
}
